#!/bin/bash
# build.sh — compile Sloth Suite into a double-clickable macOS app bundle.
#
#   ./build.sh          build and install to ~/Applications
#   ./build.sh run      build, install, and launch
#   ./build.sh test     build, then run the self-test gate (non-zero on failure)
#   ./build.sh clean    remove build artifacts
#
# The binary is built for both arm64 and x86_64 and lipo'd into a universal
# binary, so the bundle runs on an Intel Mac as well as this one.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="$ROOT/Sources/SlothSuite"
PLIST="$ROOT/Resources/Info.plist"
BUILD="$ROOT/build"
APP="$BUILD/Sloth Suite.app"
INSTALL_DIR="$HOME/Applications"
SOURCES=("$SRC_DIR"/*.swift)

FRAMEWORKS=(
  -framework Cocoa
  -framework WebKit
  -framework Network
  -framework ServiceManagement
  -framework UserNotifications
  -framework AVFoundation
)

DEPLOY_TARGET="13.0"
ARCHS=(arm64 x86_64)

case "${1:-build}" in
  clean)
    rm -rf "$BUILD"
    echo "cleaned $BUILD"
    exit 0
    ;;
esac

if [ ! -f "$SRC_DIR/SuiteController.swift" ]; then
  echo "error: expected sources in $SRC_DIR" >&2
  exit 1
fi

echo "==> compiling universal binary (${ARCHS[*]})"
rm -rf "$BUILD"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

TMP="$BUILD/.tmp"
mkdir -p "$TMP"

for arch in "${ARCHS[@]}"; do
  mkdir -p "$TMP/$arch"
  swiftc \
    -O \
    -parse-as-library \
    -target "${arch}-apple-macos${DEPLOY_TARGET}" \
    "${FRAMEWORKS[@]}" \
    -o "$TMP/$arch/SlothSuite" \
    "${SOURCES[@]}"
done

mkdir -p "$TMP/fat"
lipo -create \
  "$TMP/arm64/SlothSuite" \
  "$TMP/x86_64/SlothSuite" \
  -output "$APP/Contents/MacOS/SlothSuite"

rm -rf "$TMP"

cp "$PLIST" "$APP/Contents/Info.plist"
printf 'APPL????' > "$APP/Contents/PkgInfo"

# The Mac services helper.
#
# It exposes Apple's on-device foundation model and the Mac's own speech
# synthesiser over a loopback HTTP API. FoundationModels needs a macOS 26
# deployment target, which is why it is a separate binary rather than part
# of the shell (the shell still supports older systems).
#
# If the SDK does not have FoundationModels the build continues without it —
# the suite then falls back to Ollama and the browser's own voices.
if [ -f "$ROOT/Tools/mac-service/main.swift" ]; then
  echo "==> compiling mac-service"
  mkdir -p "$TMP/mac"
  if swiftc \
      -O \
      -target arm64-apple-macos26.0 \
      -framework FoundationModels \
      -framework AVFoundation \
      -framework Network \
      -o "$TMP/mac/mac-service" \
      "$ROOT/Tools/mac-service/main.swift" 2>/dev/null; then
    mkdir -p "$APP/Contents/MacOS"
    cp "$TMP/mac/mac-service" "$APP/Contents/MacOS/mac-service"
    chmod +x "$APP/Contents/MacOS/mac-service"
    echo "==> mac-service built (Apple on-device model + Mac voice)"
  else
    echo "note: mac-service could not be built (no FoundationModels SDK?) —"
    echo "      the suite will fall back to Ollama and the browser's voices."
  fi
  rm -rf "$TMP"
fi

# App icon (generated by Tools/make-icon.swift).
if [ -f "$ROOT/Resources/icon.icns" ]; then
  cp "$ROOT/Resources/icon.icns" "$APP/Contents/Resources/icon.icns"
else
  echo "note: Resources/icon.icns missing — run: swift Tools/make-icon.swift Resources/"
fi

# Ad-hoc sign: enough for local launch, no developer account needed.
# A Developer ID + notarisation is required before this will open on anyone
# else's Mac without a Gatekeeper prompt.
codesign --force --deep --sign - "$APP" 2>/dev/null || echo "note: ad-hoc signing skipped"

echo "==> built $APP"
lipo -info "$APP/Contents/MacOS/SlothSuite"

mkdir -p "$INSTALL_DIR"
rm -rf "$INSTALL_DIR/Sloth Suite.app"
cp -R "$APP" "$INSTALL_DIR/Sloth Suite.app"
echo "==> installed to $INSTALL_DIR/Sloth Suite.app"

if [ "${1:-build}" = "run" ]; then
  echo "==> launching"
  open "$INSTALL_DIR/Sloth Suite.app"
fi

if [ "${1:-build}" = "test" ]; then
  echo "==> running self-test"
  # The self-test exits non-zero when any assertion fails, so it works as a
  # gate. Pass --fixture <path> to pick the document used for the upload test.
  set +e
  "$APP/Contents/MacOS/SlothSuite" --selftest "$@"
  STATUS=$?
  set -e
  if [ $STATUS -eq 0 ]; then
    echo "==> self-test PASSED"
  else
    echo "==> self-test FAILED (exit $STATUS)"
  fi
  exit $STATUS
fi
